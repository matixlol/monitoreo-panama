const CANDIDATE_COMMON_NAMES_BY_NORM = new Map(
  CANDIDATE_COMMON_NAME_ENTRIES.map(([fullName, commonName]) => [
    NORM(fullName),
    { fullName: TEXT(fullName), commonName: TEXT(commonName) },
  ]),
);

export function resolveCandidateNames(rawName) {
  const fullName = TEXT(rawName);
  const match = CANDIDATE_COMMON_NAMES_BY_NORM.get(NORM(fullName));
  return {
    fullName: match?.fullName || fullName,
    commonName: match?.commonName || fullName,
  };
}
